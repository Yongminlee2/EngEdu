// ---------- 2단: 낱말 (글자 변환 뒤에 적용한다) ----------
// 글자만 바꾸면 틀리는 것들. 순서대로 적용되므로 긴 것을 먼저 둔다.
const FIX_COMMON = [
  ["隻寫", "只寫"],      // "只写 분만" — 여기의 只는 "오직"이라 隻가 아니다
  ["恢複", "恢復"],      // 되돌리다는 復
  ["關系", "關係"],      // 没关系 → 沒關係
  ["餅干", "餅乾"],      // 과자는 乾
];

// 대만 수학 교과서 용어 (홍콩에는 적용하지 않는다)
const FIX_TW = [
  ["最大公約數", "最大公因數"],
  ["公約數", "公因數"],
  ["相對頻數", "相對次數"],
  ["數量積", "內積"],
  ["概率", "機率"],
  ["數軸", "數線"],
  ["真子集", "真子集合"],
  ["子集", "子集合"],
  ["真子集合合", "真子集合"],   // 위 두 규칙이 겹칠 때의 뒤처리
];

function convert(s, extra) {
  if (!s) return s;
  let out = "";
  for (const ch of s) out += CHAR[ch] || ch;
  for (const [from, to] of FIX_COMMON) out = out.split(from).join(to);
  for (const [from, to] of extra) out = out.split(from).join(to);
  return out;
}

/** 대만 번체 */
const toTW = (s) => convert(s, FIX_TW);
/** 홍콩 번체 (글자만 번체, 용어는 본토 쪽) */
const toHK = (s) => convert(s, []);

/** 이 언어는 간체에서 자동으로 만들어 내는가? */
function derivedFrom(lang) {
  if (lang === "zh-rTW") return { base: "zh", fn: toTW };
  if (lang === "zh-rHK") return { base: "zh", fn: toHK };
  return null;
}

module.exports = { toTW, toHK, derivedFrom, CHAR };
